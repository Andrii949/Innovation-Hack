const dueTitles: Record<DueKind, string> = {
  CALIBRATION: "Wzorcowanie do zaplanowania",
  CHECK: "Sprawdzenie do wykonania",
  LOT_EXPIRY: "Partia blisko terminu ważności",
  LOW_STOCK: "Mało odczynnika",
  STOCK_COUNT: "Spis stanu do wykonania",
};

const alertStatuses = new Set<Status>(["DUE_SOON", "OVERDUE", "NO_DATA", "LOW", "COUNT_DUE"]);

const plDate = (date: string): string =>
  `${date.slice(8, 10)}.${date.slice(5, 7)}.${date.slice(0, 4)}`;

function isAddressed(item: DueItem, permission: Permission[]): boolean {
  switch (item.kind) {
    case "CALIBRATION":
    case "LOT_EXPIRY":
    case "LOW_STOCK":
      return permission.includes("calibration:write") || permission.includes("reagent:write");
    case "CHECK":
      return permission.includes("check:write");
    case "STOCK_COUNT":
      return permission.includes("stock:write");
    default:
      return false;
  }
}

